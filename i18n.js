window.pickBestLang = function (nav, keys) {
  keys = keys || Object.keys(window.LANGS || { ug:1, en:1 });
  var map = {};
  for (var i = 0; i < keys.length; i++) map[String(keys[i]).toLowerCase()] = keys[i];
  var raw = String(nav || '').replace(/_/g, '-').trim();
  if (!raw) return map.en || keys[0];
  var low = raw.toLowerCase();
  if (map[low]) return map[low];
  var parts = low.split('-');
  var primary = parts[0];
  if (primary === 'zh') {
    var script = parts.join('-');
    if (/\b(hant|tw|hk|mo)\b/.test(script)) return map.en || keys[0];
    if (map['zh-hans']) return map['zh-hans'];
  }
  if (primary === 'pt' && map['pt-br']) return map['pt-br'];
  if (map[primary]) return map[primary];
  return map.en || keys[0];
};

/* temporary English fallback for keys not yet translated */
(function () {
  function fill(dst, src) {
    if (!src || typeof src !== 'object') return;
    Object.keys(src).forEach(function (k) {
      if (typeof src[k] === 'function') { if (typeof dst[k] !== 'function') dst[k] = src[k]; }
      else if (src[k] && typeof src[k] === 'object' && !Array.isArray(src[k])) {
        if (!dst[k] || typeof dst[k] !== 'object' || Array.isArray(dst[k])) dst[k] = {};
        fill(dst[k], src[k]);
      } else if (dst[k] === undefined) dst[k] = src[k];
    });
  }
  var en = window.LANGS.en;
  Object.keys(window.LANGS).forEach(function (lg) { if (lg !== 'en') fill(window.LANGS[lg], en); });
})();

